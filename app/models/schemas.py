"""Pydantic schemas for data validation and API serialization."""

from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from app.models.enums import ChunkType


class TextChunk(BaseModel):
    """Represents a chunk of plain text extracted from a PDF page."""

    chunk_id: str = Field(..., description="Unique deterministic identifier for the chunk")
    text: str = Field(..., description="The chunked textual content")
    source_pdf: str = Field(..., description="Original filename of the source PDF")
    page_number: int = Field(..., ge=1, description="1-indexed page number in the source document")
    chunk_index: int = Field(..., ge=0, description="Sequential index of the chunk within the document/page")
    chunk_type: ChunkType = Field(default=ChunkType.TEXT, description="Type identifier for vector store filtering")
    char_count: int = Field(..., ge=0, description="Character length of the text chunk")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Arbitrary additional metadata")


class ExtractedImage(BaseModel):
    """Represents an image/chart extracted and cropped from a PDF page."""

    image_id: str = Field(..., description="Unique identifier for the extracted image")
    source_pdf: str = Field(..., description="Original filename of the source PDF")
    page_number: int = Field(..., ge=1, description="1-indexed page number where image was found")
    image_index: int = Field(..., ge=0, description="Sequential image index within the page")
    local_path: str = Field(..., description="Relative or absolute filesystem path to saved image")
    width: int = Field(..., ge=1, description="Image width in pixels")
    height: int = Field(..., ge=1, description="Image height in pixels")
    image_format: str = Field(default="png", description="File format extension (e.g. png, jpeg)")
    vlm_summary: Optional[str] = Field(default=None, description="Dense summary generated by VLM in Phase 2")
    created_at: datetime = Field(default_factory=datetime.utcnow)


class IngestedDocumentStats(BaseModel):
    """Statistical summary of an ingestion process."""

    total_pages: int = Field(default=0, ge=0)
    text_chunks: int = Field(default=0, ge=0)
    images_extracted: int = Field(default=0, ge=0)
    images_summarized: int = Field(default=0, ge=0)


class IngestionResult(BaseModel):
    """Response returned upon completing document ingestion."""

    status: str = Field(default="success")
    document_id: str = Field(...)
    filename: str = Field(...)
    stats: IngestedDocumentStats = Field(default_factory=IngestedDocumentStats)
    message: Optional[str] = None


# --- Phase 4 API Schemas ---


class QueryRequest(BaseModel):
    """Request payload for the multi-modal RAG query endpoint."""

    question: str = Field(..., min_length=2, description="User's natural language question")
    top_k: int = Field(default=5, ge=1, le=20, description="Number of relevant chunks to retrieve")
    include_sources: bool = Field(default=True, description="Whether to include retrieved source context blocks")
    filter_source: Optional[str] = Field(default=None, description="Optional PDF filename to restrict search to")


class SourceNode(BaseModel):
    """Details of a retrieved chunk or visual graphic serving as context."""

    content_preview: str = Field(..., description="Snippet of text or visual summary")
    source_pdf: str = Field(..., description="Filename of source PDF")
    page_number: int = Field(..., ge=1, description="Source page number")
    chunk_type: str = Field(..., description="'text' or 'image_summary'")
    relevance_score: float = Field(..., description="Calculated similarity score [0.0 - 1.0]")
    image_path: Optional[str] = Field(default=None, description="Filesystem path if this is an image")
    image_url: Optional[str] = Field(default=None, description="Web-accessible static image URL")


class QueryMetadata(BaseModel):
    """Execution telemetry for query retrieval and synthesis."""

    model_used: str = Field(...)
    retrieval_time_ms: float = Field(...)
    generation_time_ms: float = Field(...)
    total_sources: int = Field(...)


class QueryResponse(BaseModel):
    """Response payload returned by the multi-modal RAG endpoint."""

    question: str = Field(...)
    answer: str = Field(..., description="Synthesized answer grounded in retrieved context")
    sources: List[SourceNode] = Field(default_factory=list, description="Citations and referenced visual assets")
    metadata: QueryMetadata = Field(...)


class DocumentItem(BaseModel):
    """Summary of a document present in the vector store."""

    filename: str
    text_chunks: int
    image_chunks: int
    max_page: int


class DocumentListResponse(BaseModel):
    """Response payload listing all indexed documents."""

    documents: List[DocumentItem]
    total_count: int


class HealthResponse(BaseModel):
    """System health check and diagnostic status."""

    status: str
    app_name: str
    version: str
    chroma_connected: bool
    total_indexed_vectors: int
    embedding_engine: str
    vlm_provider: str
    vlm_live: bool
